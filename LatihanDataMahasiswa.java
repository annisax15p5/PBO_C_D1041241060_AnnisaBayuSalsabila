public class LatihanDataMahasiswa {
    public static void main (String[] args){
        //Deklarasi NIM dengan tipe data long
        long nimMahasiswa = 1041241060;
        //Deklarasi Nama dengan tipe data string
        String namaMahasiswa = "Annisa Bayu Salsabila";
        //Deklarasi Kelas dengan tipe data char
        char kelasMahasiswa = 'C';
        //Deklarasi Status Mahasiswa dengan tipe data boolean
        boolean isActive = true;
        //Deklarasi IPK Semester dengan tipe data desimal
        double ipkMahasiswa = 3.81;
        //Deklarasi total sks dengan tipe data int
        int sksMahasiswa = 64;
        //Menampilkan data Mahasiswa
        System.out.println("=== DATA MAHASISWA ===");
        System.out.println("NIM             : D" + nimMahasiswa);
        System.out.println("Nama            : " + namaMahasiswa);
        System.out.println("Kelas           : " + kelasMahasiswa);
        System.out.println("Status Aktif    : " + isActive);
        System.out.println("IPK Semester    : " + ipkMahasiswa );
        System.out.println("Total SKS       : " + sksMahasiswa );
    }
}
